# Bu program verilen saat değerini saniyeye dönüştürür.

hours = 2  # Dönüştürülecek saat sayısı
seconds_in_hour = 3600  # 1 saatteki saniye sayısı

# Saat ve toplam saniye değerlerini ekrana yazdırır
print("Hours: ", hours)
print("Seconds in Hours: ", hours * seconds_in_hour)

